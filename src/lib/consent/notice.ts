/**
 * 처리 안내 — **일정 하나만 비어 있다.**
 *
 * 폐쇄 베타를 시작하는 데 필요한 것은 다 여기 있고, 정해지지 않은 것은 **언제 끝나는가**
 * 하나뿐이다. 그 값은 표에 있어 언제든 옮길 수 있고(`current_beta_schedule`), 넣기
 * 전에는 안내가 완성되지 않는다 — 비어 있는 것을 비어 있는 채로 두는 대신 **말할 수
 * 없는 상태**로 만들어 두는 것이 요점이다.
 *
 * 「추후 종료 예정」이라고 적는 길도 있었다. 그건 약속이 아니라 미룸이고, 보유기간을
 * 「목적 달성 시까지」로 적는 것과 같은 말이 된다 — 언제인지 아무도 모른다.
 */

/**
 * 안내 문구의 판본 — **문구가 바뀌면 이 값도 바뀐다.**
 *
 * **`notice-v3` 은 화면에 서지 않는다.** 사용자가 보는 것은 「제3판 · 2026년 9월 4일
 * 시행」이다(`NOTICE_EDITION`). 처리방침의 판본은 지워서는 안 되는 정보지만 — 어느
 * 시점의 약속을 읽었는지가 거기 달렸다 — `notice-v3` 이라는 문자열은 그 물음에 답하지
 * 않는다. 우리가 기록에 쓰는 열쇠일 뿐이다.
 *
 * 바뀌면 이미 확인한 사람에게 다시 보여 준다. 「보여 준 적 있다」가 아니라 「무엇을
 * 보여 주었는가」가 남아야 그 판단을 할 수 있다.
 *
 * **날짜와 운영자는 이 판본에 없다.** 그 둘은 표의 한 줄이 들고 실행 중에 움직인다 —
 * 그래서 확인 기록이 판본과 **그 줄 번호**를 함께 든다(`notice_schedule_id`). 어느
 * 칸이 바뀌든 새 줄이 되므로, 줄을 견주면 「무엇을 보여 주었나」에 한 값으로 답한다.
 *
 * `v1` → `v2`: 국외 이전의 항목·국가·시기·목적·기간, 파기 절차와 방법, 권리 행사
 * 방법과 처리자 연락처가 새로 들어갔다. 본문이 크게 바뀌었으므로 이미 확인한 사람도
 * 다시 본다 — 판본을 안 올리면 그 사람들은 옛 문서에 동의한 채로 남는다.
 *
 * `v2` → `v3`: **인연 찾기 참여가 기본으로 켜졌다**(PRD §4.1, ADR 0037). 전에는 참여를
 * 켜는 화면이 무엇이 나가는지를 읽히는 자리였고, 그 자리를 지나지 않은 사람은 남에게
 * 보이지 않았다. 이제 내 사주를 저장하면 자동으로 후보 풀에 들므로 **그 고지가 여기로
 * 올라온다** — 켠 적 없는 참여가 생기는 것을 막는 것이 이 문단 하나다. 이미 확인한
 * 사람도 다시 보는 이유가 그것이다. 읽지 않은 사람을 풀에 넣을 수는 없다.
 */
export const NOTICE_EDITION = {
  /** 기록에 남는 값 — `app_user.notice_version` 이 이것을 든다 */
  version: 'notice-v3',
  /** 사람이 읽는 이름 */
  name: '제3판',
  /** 이 판본이 실제로 화면에 선 날 */
  effectiveFrom: '2026-09-04',
} as const;

/**
 * 기록에 남는 판본 값 — **이름과 시행일을 지나서 나온다.**
 *
 * 따로 두면 `notice-v3` 을 올리면서 이름과 날짜를 안 고치는 날이 오고, 그때 화면은
 * 새 안내를 보여주면서 옛 시행일을 말한다. 한 덩어리에서 꺼내면 그 자리가 없다.
 */
export const NOTICE_VERSION = NOTICE_EDITION.version;

/**
 * 지금 일정 — **표에서 온다**(`current_beta_schedule`).
 *
 * 코드 상수였다. 바꾸려면 배포해야 했고 그건 「언제든」이 아니다. 옮기면서 하나가
 * 따라왔다 — 날짜가 실행 중에 움직이면 **이미 안내를 본 사람은 다른 날짜를 본 사람**
 * 이므로, 확인 기록이 판본과 날짜를 함께 든다.
 *
 * 파기 기한은 DB 가 짓는다. 여기서 더하면 화면마다 더하게 되고, 그중 하나가 다른 수를
 * 더하는 날이 온다.
 */
export type BetaDates = {
  /** 베타가 끝나는 날 */
  readonly endsOn: string;
  /** 늦어도 이날까지는 파기한다 */
  readonly purgeBy: string;
  /** 종료와 파기 사이의 여유 — 문장이 이 수를 그대로 말한다 */
  readonly purgeWithinDays: number;
};


/** `2026-11-30` → `2026년 11월 30일` — 안내가 날짜를 말하는 유일한 모양 */
export const asKoreanDay = (day: string): string => {
  const [year, month, date] = day.split('-');
  return `${year}년 ${Number(month)}월 ${Number(date)}일`;
};

