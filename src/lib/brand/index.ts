export const SERVICE_TAGLINE = '나와 사람 사이를 이해하는 사주';

/** 화면 제목 뒤에 붙는 모양 — `app/layout.tsx` 의 제목 틀이 쓴다(`궁합 — 만날지도`) */
export const SERVICE_TITLE_TEMPLATE = `%s — ${SERVICE_NAME}`;
