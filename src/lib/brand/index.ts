/**
 * **서비스 이름은 여기 한 곳에서 온다**(G-58).
 *
 * 2026-09-24 에 재어 보니 서비스 이름으로 쓰는 「만세력」이 `app/` 의 27 파일에 따로 적혀 있었다 —
 * 뿌리 메타데이터 · 머리글 · 공유 미리보기 · 화면 제목 뒤의 「— 만세력」 23 자리. 기능 이름(만세력 =
 * 명식 보기, 「만세력 엔진」)과 글자가 같아서, 이름을 바꾸는 날 어느 쪽이 서비스인지 사람이 골라야 했다.
 * 그래서 서비스 이름으로 쓰는 자리는 전부 이 상수를 읽고, 기능 이름은 글자로 남는다.
 *
 * 이름은 「만날지도」다(운영자 결정 2026-10-07, ADR 0149 — 앞 이름 「점점」은 ADR 0109). 두 뜻을 겹쳐 읽는다 —
 * 「만날지도 (몰라)」(나를 돕는 사람 · 귀인을 만날지도 모른다)와 「만날 지도(地圖)」(나를 가운데 둔 관계 지도).
 * 소개팅 앱의 이름이 아니다 — 나와 맞고 나를 돕는 사람을 찾는 서비스다.
 * 로마자 표기는 MannalMap 이고 도메인 `mannalmap.com` 과 같은 철자다 — 화면에 설 자리가 아직 없어 상수로 두지 않는다.
 *
 * 처리방침 · 약관 본문의 서비스 이름은 여기서 안 바뀐다 — 고지한 판의 글자라 판을 올릴 때 사람이 고친다.
 */
