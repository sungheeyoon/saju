/**
 * **시키는 자와 막는 자가 같은 낱말을 읽는다.**
 *
 * 이 파일에는 규칙이 없다. 있는 것은 **이름 묶음**뿐이고, 그것을 읽어 가는 자리가 둘이다.
 *
 * - `prompt.ts` — 모델에게 **이 이름은 본문에 쓰지 말라고 시킨다**
 * - `check.ts` — 나온 글에 그 이름이 있으면 **저장을 막거나 판을 잰다**
 *
 * ## 왜 갈라 두나 — 이 저장소가 이미 한 번 치른 값
 *
 * 한 줄 요약의 길이가 그랬다. 검사는 60자를 막고 있었는데 **프롬프트는 길이를 한 번도
 * 말하지 않았다.** 모델이 63자를 쓰자 다 만든 글이 통째로 버려졌다 — 지킬 방법이 없는
 * 계약을 검사만 들고 있었던 것이다. 토큰은 나가고 글은 안 남았다.
 *
 * 그래서 `READING_POLICY.metaphorLength` 가 **시키는 값(`target`)과 막는 값(`max`)을 한
 * 상수에서** 내주게 고쳤다. 이 파일은 낱말에 대해 같은 일을 한다.
 *
 * ## 갈래로 두는 까닭 — 두 표가 같은 낱말을 다르게 쓴다
 *
 * 한 목록으로 두면 안 된다. 저장을 막는 표(`OUT_OF_SCOPE_TERMS`)와 판을 재는 표
 * (`PLAIN_FORBIDDEN_TERMS`)는 **겨누는 것이 달라 각자 더 드는 낱말이 있다.** 둘이 함께
 * 드는 것만 여기 있고, 한쪽만 드는 것은 그 표 옆에 남는다.
 *
 * 프롬프트가 읽어 가는 것은 **그 가운데 일부**다. 금지 낱말을 통째로 나열하지 않는다 —
 * 「모델이 먼저 읽는 것은 목록이다」가 이 저장소의 규율이고, 목록을 길게 세울수록 글이
 * 점검표처럼 딱딱해진다. 프롬프트는 **지금 그 자료에 실린 판정의 이름**만 부른다.
 */
export const SAJU_TERMS = {
  /** 한 사람의 원국이 센가 약한가 — 확장형 궁합에 실리는 판정이다 */
  strength: ['신강', '신약'],
  /** 무엇으로 보태는가 — 확장형에 `eokbuMatch` 로 실린다. 이름은 둘이 함께 다닌다 */
  eokbu: ['억부', '용신'],
  /** 같은 용신 계열이지만 **어느 궁합 자료에도 안 실리는** 갈래 */
  method: ['격국', '조후'],
  /** 때를 부르는 이름 — 인연 궁합 자료에는 없다 */
  luck: ['대운', '세운', '월운'],
  /**
   * 신살 — **이름이 아니라 하는 일로 쓰게 한다.**
   *
   * 여기 있는 것은 두 표가 함께 드는 것뿐이다. 한쪽만 드는 것(`천덕귀인`·`월덕귀인` ·
   * `고신`·`과숙`)은 그 표 옆에 그대로 남는다.
   */
  sinsal: [
    '신살',
    '천을귀인',
    '문창귀인',
    '학당귀인',
    '역마',
    '도화',
    '화개',
    '공망',
    '백호',
    '괴강',
    '양인',
  ],
} as const;

/** 프롬프트가 한 줄에 적는 이름 — 손으로 옮겨 적지 않는다 */
export const termNames = (...groups: readonly (keyof typeof SAJU_TERMS)[]): string =>
  groups.flatMap((group) => [...SAJU_TERMS[group]]).join('·');
