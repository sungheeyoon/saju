/**
 * 조후용신(調候用神) 참고표.
 *
 * 《窮通寶鑑》은 일간 10 × 월지 12를 각각 따로 논한다. 같은 여름·겨울이라도
 * 필요한 것이 한 오행으로 환원되지 않고, 원국의 수·화·토·금 분포와 월의
 * 상·하순에 따라 우선순위가 바뀐다. 따라서 이 표는 `stems`와 짧은 조건을
 * 함께 보존한다.
 *
 * 출처:
 * - 원문: https://zh.wikisource.org/wiki/窮通寶鑑
 * - 120칸 대조표: https://www.douban.com/note/204554812/
 *
 * 대조표의 명백한 전사 오류(丁午의 寅→庚, 辛丑의 누락된 丙 등)는 원문으로
 * 바로잡았다. `stems` 순서는 대표적인 검토 순서이지, 뒤의 천간이 언제나 앞의
 * 천간보다 덜 중요하다는 뜻은 아니다. 조건이 붙은 칸은 반드시 `note`를 함께
 * 읽어야 한다.
 */

export type JohuRule = {
  /** 검토할 천간. 조건에 따라 함께 쓰거나 앞뒤가 바뀔 수 있다 */
  stems: readonly Stem[];
  /** 원문의 조건을 계산기가 단정하지 않도록 남긴 짧은 요약 */
  note: string;
  /**
   * 원문이 상반월·하반월을 갈라 말하는 칸에만 있다(120칸 중 여섯).
   *
   * 이것만은 자동으로 판정할 수 있다. 중기가 절의 정확히 +15° 지점이라
   * 경계가 천문으로 정해지기 때문이다. "수가 왕하면 戊" 같은 세력 조건은
   * 문턱을 지어내야 하므로 여기 없고 `note` 에 그대로 남는다.
   */
  halfMonth?: { first: readonly Stem[]; second: readonly Stem[] };
};

const rule = (
  stems: readonly Stem[],
  note: string,
  halfMonth?: JohuRule['halfMonth'],
): JohuRule => (halfMonth ? { stems, note, halfMonth } : { stems, note });

