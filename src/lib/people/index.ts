/**
 * 내가 등록한 사람과 **나 사이의 관계.**
 *
 * `src/lib/consent` · `src/lib/discovery` 와 같은 자리에 선다 — 정책이 값과 문장을
 * 들고, 화면은 그것을 앞에 세우기만 한다.
 *
 * ## 왜 이 값이 필요한가
 *
 * 궁합 풀이가 **두 사람이 무슨 사이인지 모른 채** 쓰이고 있었다. 그래서 어머니와의
 * 궁합에 「처음에 끌리는 지점」과 「가까워질수록」이 나갔다. 모델이 지어낸 것이 아니라
 * 자료에 없어서 관계의 일반적 가능성으로 읽은 것이고, 실제로 모델이 스스로
 * 「자료에는 두 사람이 연인인지 동료인지 가족인지가 없습니다」라고 적었다.
 *
 * ## 무엇에 붙는가 — **사람이 아니라 나와 그 사람 사이**
 *
 * `local_label` 과 같은 자리(`user_person_access`)에 붙는다. 같은 사람이 누군가에겐
 * 어머니고 누군가에겐 친구다. Person 에 붙이면 그 사람이 「가족」이라는 속성을 가진
 * 것이 되고, 그것은 우리가 아는 사실이 아니다.
 *
 * ## 안 하는 것
 *
 * **판정에 넣지 않는다.** 관계는 글의 장면과 조언을 고르는 값이지 점수를 움직이는
 * 값이 아니다. 넣기 시작하면 「가족이라 78점」 같은 것이 나오고, 그것은 근거가 아니라
 * 우리가 지어낸 규칙이다.
 */

/** 고를 수 있는 갈래 — 이름은 DB 의 검사식과 같다 */
export const RELATIONS = ['family', 'friend', 'partner'] as const;
export type Relation = (typeof RELATIONS)[number];

/**
 * 고르는 칸에 서는 말.
 *
 * 셋으로 묶은 것은 **프롬프트가 읽을 수 있는 만큼**만 나누기 위해서다. 부모·자녀·형제를
 * 따로 두면 고르는 칸이 길어지는데, 글이 달라지는 지점은 「가족인가 연인인가」이지
 * 「어머니인가 이모인가」가 아니다. 더 잘게 나눠야 할 이유가 자료에서 나오면 그때 나눈다.
 *
 * ## 「그 밖」을 두지 않는다
 *
 * 넷이던 때 「그 밖」과 「아직 모르겠음」이 나란히 서 있었는데, **둘이 같은 말이었다.**
 * 프롬프트에 나가는 문장도 양쪽 다 「어느 쪽으로도 단정하지 마라」였다.
 *
 * 지운 쪽이 「그 밖」인 이유는, 안 고른 상태는 **어차피 있어야 하기 때문**이다 — 고르기
 * 전의 기본값이고, 라디오를 되돌리는 유일한 길이다. 「그 밖」은 저장되는 값을 하나
 * 늘리면서 글은 안 바꾼다.
 */
export const RELATION_LABEL: Record<Relation, string> = {
  family: '가족',
  friend: '친구·동료',
  partner: '연인·배우자',
};

/** 고르는 칸 아래에 서는 말 — 왜 묻는지 밝힌다 */
export const RELATION_INTRO =
  '두 사람의 궁합을 풀 때 어떤 사이인지에 따라 읽어 줄 장면이 달라집니다. 이 값은 점수에 쓰지 않습니다.';

/**
 * 모델에게 넘길 말 — **화면의 말과 갈라 둔다.**
 *
 * 화면은 「친구·동료」라고 짧게 쓰지만 모델에게는 무엇을 하라는 것인지까지 말해야
 * 한다. 두 말을 한 값으로 묶으면 화면을 다듬을 때 프롬프트가 함께 움직인다.
 */
export const RELATION_FOR_PROMPT: Record<Relation, string> = {
  family: '가족이다. 연애의 장면으로 읽지 말고, 오래 같이 살아온 사이에서 되풀이되는 것으로 읽어라',
  friend: '친구이거나 함께 일하는 사이다. 연애의 장면으로 읽지 마라',
  partner: '연인이거나 배우자다',
};

/**
 * 관계를 **모를 때** 모델에게 하는 말.
 *
 * 모른다를 값으로 든다. 이 값이 없던 시절에 등록한 사람은 계속 있고, 두 관리 Person
 * 끼리의 궁합은 애초에 알 수가 없다 — 저장한 것은 「나와 그 사람」이지 「그 둘」이
 * 아니기 때문이다. 그때 자기 풀이 때처럼 조용히 넘기면 모델은 **다시 연애로 읽는다.**
 */
export const RELATION_UNKNOWN =
  '무슨 사이인지 모른다. 연인·가족·동료 중 어느 쪽으로도 단정하지 말고, 어느 사이에나 해당하는 장면으로 읽어라';

/** 인연 찾기로 만나 서로 동의한 두 사람 — 고르는 값이 아니라 **성립 방식이 정한다** */
export const RELATION_FROM_MATCH =
  '인연 찾기에서 만나 서로 상세 궁합에 동의한 사이다. 아직 서로를 잘 모르는 두 사람이다';

/**
 * 프롬프트에 실을 문장 — **모를 때도 한 문장이 나간다.**
 *
 * 자리를 비우면 모르는 것과 안 물어본 것이 같은 침묵이 되고, 모델은 그 침묵을
 * 연애로 읽는다. 그것이 이 값을 만든 까닭이다.
 *
 * 우리가 부르는 프롬프트와 사용자가 복사해 가는 프롬프트가 **같은 문장**을 쓴다.
 * 두 자리에 따로 적으면 한쪽만 고쳐지고, 그때 어느 쪽이 우리 뜻인지 알 수 없다.
 */
export const relationSentence = (relation: Relation | null): string =>
  relation === null ? RELATION_UNKNOWN : RELATION_FOR_PROMPT[relation];

/**
 * 관계가 프롬프트에서 하는 일 — **장면을 고르되 점수는 안 건드린다.**
 *
 * 두 프롬프트가 이 문단을 함께 쓴다. 「점수는 이 값으로 움직이지 않는다」를 한 곳에만
 * 적으면, 안 적힌 쪽에서 모델이 「가족이라 78점」을 낸다.
 */
export const relationBlock = (said: string): string => `## 두 사람은 무슨 사이인가

${said}.

이 값으로 **장면과 조언을 고른다.** 같은 근거라도 가족에게 할 말과 연인에게 할 말이
다르다 — 연락 습관, 돈 쓰는 방식, 부딪히는 자리가 관계마다 다른 얼굴로 나온다.

**점수는 이 값으로 움직이지 않는다.** 관계가 무엇이든 두 원국 사이의 사실은 같다.
「가족이라 잘 맞는다」처럼 관계 자체를 근거로 쓰지 마라.`;

/** 모르는 값은 모르는 채로 둔다 — 그럴듯한 쪽으로 눕히지 않는다 */
export const relationOf = (raw: string | null | undefined): Relation | null =>
  RELATIONS.find((known) => known === raw) ?? null;


/**
 * 저장할 자리 — **DB 가 세어 내준다**(`my_person_slots`).
 *
 * 수를 여기 적지 않는다. 한도는 트리거가 걸고 그 수는 `person_limit()` 이 든다.
 * 화면이 그 수를 손으로 베껴 들면 한도를 옮기는 날 화면만 옛 수를 말한다.
 */
export type PersonSlots = {
  readonly limit: number;
  readonly used: number;
  readonly remaining: number;
};

/**
 * 자리가 모자라서 못 저장할 때 하는 말 — **모자라지 않으면 `null`.**
 *
 * 저장하는 입구가 셋이다(사람 탭 · 사주 결과 아래 · 궁합 결과 아래). 말을 각자 지으면
 * 한 자리는 「한 명을 지워야 합니다」라 하고 다른 자리는 조용히 실패한다. 그리고 조용히
 * 실패하는 쪽이 사용자에게는 **풀이가 안 되는 앱**이다.
 *
 * @param needed 이 입구가 저장하려는 사람 수. 사주풀이는 하나, 궁합은 둘이다.
 * @param slots 지금 자리 — **못 읽었으면 `null` 을 넘긴다.** 그때는 막지 않는다:
 *   읽기가 한 번 실패했다고 「다 찼다」고 말하면 그것은 거짓이고, 저장은 어차피 DB 가
 *   막는다. 여기서 하는 일은 먼저 말해 주는 것이지 판정이 아니다.
 *
 * **둘이 필요한데 하나 남은 자리도 못 저장한다.** 한 문으로 저장하므로 첫 사람이
 * 들어가고 둘째에서 막히면 둘 다 되돌아간다 — 눌러 봐야 아무 일도 안 일어난다.
 */
export const noRoomToSave = (needed: number, slots: PersonSlots | null): string | null => {
  if (slots === null || slots.remaining >= needed) return null;

  return slots.remaining === 0
    ? `저장한 사람이 ${slots.limit}명을 다 채웠습니다. 한 명을 지워야 여기서 저장할 수 있습니다.`
    : `저장한 사람이 ${slots.used}명이라 자리가 ${slots.remaining}명분만 남았습니다. ${needed}명을 저장하려면 ${
        needed - slots.remaining
      }명을 지워야 합니다.`;
};
