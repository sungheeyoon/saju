/**
 * 주소로 들어온 id 의 모양 — **틀린 모양은 「없는 것」과 같은 답이다.**
 *
 * 사람 상세·인연 결과·검산 세 자리가 같은 식을 한 벌씩 적고 있었다.
 */
export const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/**
 * **서버가 지어 내준 id 를 돌려받는 자리** — 소문자만 받는다. 로그인 전 사주 문단의 세션 id(`app/taste/`)는 DB 가 지은 것이라
 * 대문자 꼴은 우리가 내준 적이 없다. 두 파일에 세 벌로 적혀 있던 것을 모았다(G-109) — 대소문자를 가리는 뜻은 그대로다.
 */
export const LOWERCASE_UUID = new RegExp(UUID.source);
