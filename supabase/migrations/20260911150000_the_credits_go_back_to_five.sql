-- ---------------------------------------------------------------------------
-- 풀이권 여덟에서 다시 **다섯**으로
-- ---------------------------------------------------------------------------

/**
 * 같은 날 여덟으로 올렸다가(`20260911120000`) 되돌린다. **사람이 정했다.**
 *
 * 올린 근거는 셈이었다 — 내 사주 하나, 저장한 사람 하나, 그 둘의 궁합 하나면 셋이고,
 * 남은 둘로 인연 요청을 띄우면 그 둘은 답이 올 때까지 **예약**으로 묶인다(ADR 0038).
 *
 * 그 셈이 틀렸다는 것이 아니라, **테스트를 다섯으로 시작하기로 한 것**이다. 되돌리면서
 * 그 제약은 그대로 남으므로 여기 적어 둔다 — 다음에 이 수를 볼 사람이 같은 셈을 다시
 * 하지 않도록.
 *
 *     요청 둘을 띄운 사람은 그 답이 올 때까지 자기 풀이를 하나도 못 만든다.
 *
 * 테스터가 매칭을 한 바퀴(요청 · 거절 · 다시 요청) 밟아 보려는 자리에서 이 벽을 만난다.
 * 만나면 그때 올린다 — **올리기는 쉽고 내리기는 어렵다.** 이미 여섯 개를 쓴 사람의
 * 여섯째를 우리가 회수할 수는 없다(ADR 0032 의 저장 한도와 같은 성질이다).
 *
 * ## 부등식은 그대로 산다
 *
 *     저장 자리(10) > 풀이권 총량(5)
 *
 * 여덟일 때도 참이었고 다섯이면 더 넉넉하다(ADR 0032).
 *
 * ## 이미 쓴 사람에게는 아무 일도 안 일어난다
 *
 * 풀이권은 **적어 두지 않고 센다**(ADR 0021). 잔액을 든 열이 없으므로 이 함수 하나를
 * 바꾸면 그 순간부터 모두의 잔액이 다시 계산된다. 다만 **이미 여섯 이상 쓴 사람이
 * 있었다면** 그 사람의 남은 수는 0이 되고 음수로는 안 내려간다(`greatest(0, …)`).
 * 오늘 올렸다 내리는 것이라 그런 사람은 없다 — 있는지 확인하고 내린다.
 */
create or replace function public.reading_credit_limit()
returns integer
language sql
immutable
as $$ select 5 $$;

-- `create or replace` 는 권한을 그대로 두지만, 이 파일만 읽고는 누가 부를 수 있는지
-- 알 수 없다. 다시 적어 둔다 — 상수를 내주는 함수라도 닫는다.
revoke execute on function public.reading_credit_limit()
  from anon, public, authenticated, service_role;
