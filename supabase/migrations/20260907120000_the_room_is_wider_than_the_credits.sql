-- ---------------------------------------------------------------------------
-- 저장 자리는 **언제나 풀이권보다 넓다** (ADR 0032)
-- ---------------------------------------------------------------------------

/**
 * 스물에서 **열**로.
 *
 * 처음 스물을 정한 근거는 「풀이권이 다섯인데 스물은 쓸 일이 없다」였다. 그 문장은 오래
 * 못 간다 — 풀이권을 스물로 올리는 날 거짓이 되고, 그때 이 수는 이유 없는 수 하나로 남는다.
 * 그래서 정하는 것은 수가 아니라 **관계**다.
 *
 *     저장 자리 > 풀이권 총량
 *
 * ADR 0030 이 「AI 로 가는 길은 저장 하나」로 정한 뒤부터 이 부등식은 제품이 성립하는
 * 조건이 됐다. 자리가 풀이권보다 적으면 **풀이권을 가지고도 쓸 데가 없는 사람**이 생기고,
 * 그 사람에게 앱은 눌러도 아무 일이 안 일어나는 물건이다. 부등식이 깨지는 날 다시 열어야
 * 하는 것은 저장 한도가 아니라 **저장 없이 풀이 받기**다(PRD §1).
 *
 * 열은 그 부등식을 지키는 가장 작은 수가 아니라 **목록이 읽히는 동안의 수**다. 궁합 고르는
 * 칸이 `select` 둘인데 스물이 들어가면 그 칸이 먼저 망가진다. 올리기는 쉽고 내리기는
 * 어렵다 — 이미 열다섯을 저장한 사람의 열다섯 번째를 우리가 지울 수는 없다.
 *
 * ## 이미 넘긴 계정은 그대로 둔다
 *
 * 트리거는 `insert` 만 본다. 스물을 채운 계정은 스물인 채로 남고 하나도 더 못 넣는다.
 * **지우지 않는다** — 사용자가 저장한 것을 우리가 정책 변경으로 없애는 것은 자리를 아끼는
 * 것보다 나쁘다. `my_person_slots().remaining` 이 이미 `greatest(0, …)` 라 화면은 음수를
 * 말하지 않고 자리가 없다고만 한다.
 *
 * ## 고치는 자리가 하나다
 *
 * 함수 하나뿐이다. 트리거도 거절 문장도 화면도 이 함수를 읽는다 — 하루 전에 상수를 함수로
 * 세운 것이(`20260907090000`) 바로 이 날을 위한 것이었다.
 */
create or replace function public.person_limit()
returns integer
language sql
immutable
as $$ select 10 $$;

-- `create or replace` 는 권한을 그대로 두지만, 이 파일만 읽고는 누가 부를 수 있는지
-- 알 수 없다. 다시 적어 둔다 — 상수를 내주는 함수라도 닫는다.
revoke execute on function public.person_limit()
  from anon, public, authenticated, service_role;
