-- ---------------------------------------------------------------------------
-- 풀이권 다섯에서 **여덟**으로
-- ---------------------------------------------------------------------------

/**
 * 다섯으로는 **매칭을 한 바퀴 못 돈다.**
 *
 * 세어 보면 이렇다. 내 사주 하나, 저장한 사람 하나, 그 둘의 궁합 하나 — 여기까지 셋이다.
 * 남은 둘로 인연 요청을 띄우면 그 둘은 **예약**이라 답이 올 때까지 묶여 있고(ADR 0038),
 * 그동안 다시 만들어 보는 일도 못 한다. 요청이 하나라도 거절되면 그 자리를 다시 쓰기까지
 * 테스터가 할 수 있는 것이 없다.
 *
 * 여덟이면 위의 셋을 하고도 요청 셋을 띄운 채 둘이 남는다. **재시도 한 번과 실패 한 번이
 * 들어갈 자리**가 그 둘이다 — 테스트에서 실제로 재어 보려는 것이 그 자리이기 때문이다.
 *
 * ## §2 의 부등식은 산다
 *
 *     저장 자리(10) > 풀이권 총량(8)
 *
 * ADR 0032 가 정한 관계다. 풀이를 받으려면 대상이 저장돼 있어야 하므로, 자리가 풀이권보다
 * 적으면 풀이권을 가지고도 쓸 데가 없는 사람이 생긴다. 여덟은 그 부등식 안이다 — 열보다
 * 크게 올리는 날에는 **저장 한도를 먼저 올려야 한다.**
 *
 * ## 비용은 빗장이 든다
 *
 * 사람당 여덟이 하루 상한(100회)을 밀지 않는다. 그 값은 사람당이 아니라 전체이고
 * (ADR 0039), 여기서 올리는 것은 **한 사람이 평생 몇 번 만드는가**이지 하루에 몇 번
 * 만드는가가 아니다. 시간당 상한(20회)도 그대로다.
 */
create or replace function public.reading_credit_limit()
returns integer
language sql
immutable
as $$ select 8 $$;

-- `create or replace` 는 권한을 그대로 두지만, 이 파일만 읽고는 누가 부를 수 있는지
-- 알 수 없다. 다시 적어 둔다 — 상수를 내주는 함수라도 닫는다.
revoke execute on function public.reading_credit_limit()
  from anon, public, authenticated, service_role;
