-- 종료일을 정한다 — **2026년 10월 31일**
--
-- 이 값이 없는 동안에는 안내가 만들어지지 않아 아무도 시작할 수 없었다(ADR 0024).
-- 이 줄이 그 문을 연다.
--
-- **초대와 무관한 고정일이다.** 언제 몇 명을 초대하든 그날 끝난다 — 초대에서 며칠을
-- 세는 값이 아니므로 테스터를 늦게 넣었다고 자동으로 밀리지 않는다. 밀려면 새 줄을
-- 넣는다(표는 쌓는다).
--
-- 파기 기한은 여기서 나온다: 2026-10-31 + 30일 = **2026-11-30**.
--
-- ## 왜 마이그레이션인가
--
-- 이 값은 배포 없이 옮기라고 표에 둔 것이다. 그런데 **첫 값**은 다르다 — 그날부터
-- 사용자에게 한 약속이 시작되므로, 무엇을 처음 약속했는지가 이력에 남아야 한다.
-- 옮기는 것은 SQL 한 줄이고(runbook), 그 이력은 표가 든다.
--
-- `where not exists` 인 것은 **운영자가 옮긴 값을 되돌리지 않으려는** 것이다. 이미 정한
-- 곳에서는 아무 일도 하지 않는다.
insert into public.beta_schedule (ends_on, purge_within_days, note)
select '2026-10-31'::date, 30, '고정 종료일 — 초대 시점과 무관하다'
where not exists (select 1 from public.beta_schedule);
