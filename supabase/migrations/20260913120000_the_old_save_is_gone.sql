-- ---------------------------------------------------------------------------
-- 옛 `save_reading` 을 지운다 — 넓혔던 것을 좁힌다
-- ---------------------------------------------------------------------------
--
-- 앞 마이그레이션(`20260913090000`)이 비유를 받는 열두 인자짜리를 세우면서 **옛 열한
-- 인자짜리를 일부러 남겼다.** 같이 지우면 어느 순서로 배포해도 창이 생기기 때문이다 —
-- 마이그레이션이 먼저면 그때 떠 있는 앱이 없어진 함수를 부르고, 배포가 먼저면 새 앱이
-- 아직 없는 함수를 부른다. 그 창에 들어온 호출은 **모델은 이미 돌았는데 글은 안 남는다.**
--
-- ## 좁혀도 되는 것을 재고 나서 지운다
--
-- 「배포했으니 됐겠지」로 지우지 않는다. 프로덕션에서 셋을 봤다.
--
--   1. 새 판본으로 저장된 글이 실제로 비유를 들고 있다 — `self`·`private` 둘 다
--   2. 도는 시도가 0 이다 — 옛 길로 저장을 마치려는 호출이 없다
--   3. 마지막 시도가 성공했다(`reading-prompt-v7`)
--
-- 셋이 다 참이라 옛 문을 쓰는 것이 남아 있지 않다.
--
-- ## 지운 뒤에 무엇이 달라지나
--
-- **아무것도 안 달라진다.** 부르는 쪽은 이미 열두 인자로 부르고 있었고, 이 줄은 그
-- 사실을 되돌릴 수 없게 만드는 것뿐이다. 두 벌이 서 있는 동안에는 「어느 쪽으로도
-- 저장될 수 있다」가 참이었고, 그 상태에서는 비유 없는 글이 조용히 섞여 들어올 길이
-- 열려 있었다.

drop function public.save_reading(
  uuid, uuid, uuid, text, smallint, text, text, text, text, jsonb, timestamptz
);
