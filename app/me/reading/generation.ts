/**
 * 지금 쓰는 모델과 **우리가 정한 생성 설정.**
 *
 * ## 왜 부르는 코드와 따로 서는가
 *
 * 「무엇으로 만든 것인가」는 결과 옆에 남아야 참이다 — 저장된 artifact 도, 실호출
 * 검사가 떨구는 원문도 이 값을 함께 싣는다. 그런데 그 자리들이 모델을 부르는 모듈에서
 * 읽어 오면 provider SDK 가 딸려 온다.
 *
 * 그렇다고 사람이 손으로 적게 두면 이 저장소가 되풀이해 지킨 규칙이 여기서만 깨진다 —
 * **손으로 적을 자리를 남기지 않는다.** 모델 이름을 한 글자 잘못 적은 기록은 나중에
 * 그것이 오타였다는 것조차 알 방법이 없다.
 *
 * 그래서 값만 여기 세운다. 부르는 쪽(`model.ts`)이 이것을 들고 간다. **자리가 하나다.**
 *
 * `settings` 에는 **우리가 정한 것만** 적는다. 온도를 안 적은 것은 값이다 — 그 값은
 * provider 기본값이라는 뜻이고, 안 정한 것을 정한 척 적어 두면 나중에 그 숫자를 근거로
 * 결과를 견주게 된다.
 */
export const GENERATION = {
  model: 'gpt-5.6-luna',
  provider: 'openai-responses-api',
  settings: {
    /** OpenAI Responses API 에 응답을 별도로 저장하지 않는다 */
    store: false,
    /**
     * **기다리다 마는 자리를 우리가 정한다.**
     *
     * 안 정하면 플랫폼이 요청을 끊는 순간이 상한이 되고, 그때는 실패를 기록할 코드가
     * 아예 안 돈다 — 시도가 `running` 인 채로 남는다. DB 가 그 행을 만료로 닫아 주지만
     * (`reading_run_timeout`), 그 전에 **우리 손으로 끝내고 실패를 적는 것**이 맞다.
     * 이 값은 그 만료보다 짧아야 뜻이 있다.
     */
    timeout: 240_000,
  },
} as const;
