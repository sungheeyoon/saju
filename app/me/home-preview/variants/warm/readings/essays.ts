const ESSAYS: Record<string, Essay> = {
  self: SELF,
  'preview-mom': MOM,
  'preview-jun': JUN,
  'preview-seo': SEO,
};

export function essayOf(key: string): Essay {
  return ESSAYS[key] ?? FALLBACK;
}

/** 읽는 데 걸리는 분 — 한국어 산문 1분 약 500자로 잰다 */
export function minutesOf(essay: Essay): number {
  const chars = essay.lead.length + essay.sections.reduce((sum, one) => sum + one.heading.length + one.paragraphs.join('').length, 0);
  return Math.max(1, Math.round(chars / 500));
}
